#!/usr/bin/env python3
"""Generate Grid32/grid32_case.h: Unicode simple case mapping for the BMP.

    python3 Tests/tools/gen_grid32_case.py > Grid32/grid32_case.h

The formula engine upper- and lower-cases text (UPPER, LOWER) and compares it
case-insensitively. The C library's towupper/towlower follow a locale the
program never sets, so results differed by platform and machine: on Linux
UPPER("héllo") was "HéLLO". This table makes case mapping the same
everywhere.

Mappings are the simple (one character to one character) ones, so text keeps
its length: "ß" has no one-character uppercase and stays "ß". Only the Basic
Multilingual Plane is covered, so Windows (16-bit wchar_t) and Linux (32-bit)
map exactly the same characters.

The data is Python's unicodedata; a character is mapped when its full
uppercase (lowercase) form is a single character. The Unicode version is
recorded in the header.
"""
import sys
import unicodedata


def mapping(f):
    pairs = []
    for c in range(0x10000):
        if 0xD800 <= c < 0xE000:
            continue
        m = f(chr(c))
        if len(m) == 1 and ord(m) != c and ord(m) < 0x10000:
            pairs.append((c, ord(m) - c))
    return pairs


def runs(pairs):
    """Group (code point, delta) into runs: first..last, every `stride`-th
    code point, all with the same delta. Stride 1 covers blocks like a..z,
    stride 2 the alternating upper/lower pairs of Latin Extended."""
    out = []
    for c, d in pairs:
        if out:
            first, last, stride, delta = out[-1]
            if delta == d:
                if stride == 0 and c - last in (1, 2):
                    out[-1] = [first, c, c - last, delta]
                    continue
                if stride and c - last == stride:
                    out[-1][1] = c
                    continue
        out.append([c, c, 0, d])
    for r in out:
        if r[2] == 0:
            r[2] = 1
    return out


def table(name, rs):
    lines = [f"    static const CaseRun {name}[] = {{"]
    for first, last, stride, delta in rs:
        lines.append(f"        {{ 0x{first:04X}, 0x{last:04X}, {stride}, {delta} }},")
    lines.append("    };")
    return "\n".join(lines)


def lookup(rs, c):
    """What the generated C++ Map() does, to check the table before writing it."""
    import bisect
    i = bisect.bisect_right([r[0] for r in rs], c)
    if i == 0:
        return c
    first, last, stride, delta = rs[i - 1]
    if c > last or (c - first) % stride:
        return c
    return c + delta


def checked(f):
    pairs = mapping(f)
    rs = runs(pairs)
    want = dict(pairs)
    for c in range(0x10000):
        expect = c + want.get(c, 0)
        got = lookup(rs, c)
        if got != expect:
            sys.exit(f"table check failed at U+{c:04X}: {got:#x} != {expect:#x}")
    return rs


upper = checked(str.upper)
lower = checked(str.lower)

print(f"""#pragma once
// GENERATED by Tests/tools/gen_grid32_case.py from Unicode {unicodedata.unidata_version}
// (Python {sys.version.split()[0]}). Do not edit by hand; rerun the script.
//
// Unicode simple case mapping for the Basic Multilingual Plane, independent
// of the C library's locale: the formula engine's UPPER, LOWER and
// case-insensitive comparisons give the same answer on every platform.
// One character maps to one character (sharp s, U+00DF, stays as it is), so text keeps its
// length; characters outside the BMP are left as they are.

namespace Grid32Detail {{

namespace CaseData {{
    // Code points first..last, every `stride`-th one, map to code point + delta.
    struct CaseRun {{ unsigned short first, last; unsigned char stride; int delta; }};

{table("kToUpper", upper)}

{table("kToLower", lower)}

    template <size_t N>
    inline wchar_t Map(const CaseRun (&runs)[N], wchar_t ch)
    {{
        const unsigned long c = (unsigned long)ch;
        if (c > 0xFFFF) return ch;
        // The last run starting at or before c.
        size_t lo = 0, hi = N;
        while (lo < hi)
        {{
            const size_t mid = (lo + hi) / 2;
            if (runs[mid].first <= c) lo = mid + 1; else hi = mid;
        }}
        if (lo == 0) return ch;
        const CaseRun& r = runs[lo - 1];
        if (c > r.last || (c - r.first) % r.stride != 0) return ch;
        return (wchar_t)((long)c + r.delta);
    }}
}}

// The character in upper (lower) case, or itself.
inline wchar_t ToUpperChar(wchar_t ch)
{{
    if (ch < 0x80) return (ch >= L'a' && ch <= L'z') ? (wchar_t)(ch - 32) : ch;
    return CaseData::Map(CaseData::kToUpper, ch);
}}

inline wchar_t ToLowerChar(wchar_t ch)
{{
    if (ch < 0x80) return (ch >= L'A' && ch <= L'Z') ? (wchar_t)(ch + 32) : ch;
    return CaseData::Map(CaseData::kToLower, ch);
}}

}} // namespace Grid32Detail""")
